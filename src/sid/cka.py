"""Linear CKA (Centered Kernel Alignment, Kornblith et al. 2019) между
представлениями двух глубин — используется и как диагностика (насколько
похожи/линейно связаны h_i и h_j), и как дифференцируемый штраф в лоссе
(см. memory.md, запись про "штраф за излишнюю линейность между блоками").

CKA(X,Y) = ||Xc^T Yc||_F^2 / (||Xc^T Xc||_F * ||Yc^T Yc||_F)

X, Y — (n, d) матрицы представлений (n = B*T позиций, d = n_embd), центрированные
по столбцам. Значение в [0,1]: 1 — представления совпадают с точностью до
поворота/масштаба (полностью взаимно предсказуемы линейно), 0 — совсем не
похожи. Считается на скрытых состояниях (n_embd=272), а не на логитах
(vocab=16384) — полный (B,T,V) тензор здесь не нужен вообще, chunking не
требуется по памяти.
"""

import torch


def linear_cka(x, y, eps=1e-8):
    """x, y: (n, d) — уже сплющенные по (B,T) представления двух глубин.
    Градиент течёт в оба аргумента (вызывающий код сам решает, какой из них
    detach'нуть, чтобы не нарушить stop-gradient изоляцию между блоками)."""
    x = x - x.mean(dim=0, keepdim=True)
    y = y - y.mean(dim=0, keepdim=True)
    cross = x.T @ y  # (d, d)
    xx = x.T @ x
    yy = y.T @ y
    hsic_xy = (cross ** 2).sum()
    hsic_xx = (xx ** 2).sum()
    hsic_yy = (yy ** 2).sum()
    return hsic_xy / (torch.sqrt(hsic_xx * hsic_yy) + eps)
